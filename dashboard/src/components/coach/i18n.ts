export const DICT: Record<Lang, Record<Key, string>> = { en, he }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = DICT[lang][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function junkReason(lang: Lang, reason: string) {
  return lang === 'he' ? (JUNK_HE[reason] ?? reason) : reason
}
